test("old saved settings keep unsaved axes and optional-field defaults without promoting legacy creation flags", () => {
  const result = recoverSettings(OLD_JSON, EN)!;
  assert.deepEqual(result.invalid, []);
  assert.equal(result.config.schema, 2);
  assert.equal(result.config.preset, "tough-love");
  assert.equal(result.config.unsaved, true);
  assert.deepEqual(result.config.axes, {
    formality: 1, verbosity: 4, profanity: 2, playfulness: 5,
    critique: 2, flattery: 1, warmth: 2, conviction: 4,
    care: 5, compliance: 3, refusal: 1, bravado: 1,
  });
  assert.deepEqual(result.config.persona, {
    age: "40s", gender: "neutral", note: "Dummy private role",
    address: { self_ref: "Dummy Agent", user_ref: "Dummy Reader" },
    user: null, agent: null,
  });
  assert.equal(result.config.safeword, "dummy plain answer");
  assert.equal(Object.hasOwn(result.config, "guards"), false);
  assert.equal(result.config.speech_level, "polite");
  assert.equal(result.config.language, "ko");
  assert.equal(Object.hasOwn(result.config, "fixed_width"), false);
  assert.ok(!result.defaulted!.includes("fixed_width"));
  assert.ok(result.defaulted!.includes("persona.user"));
  assert.ok(result.defaulted!.includes("persona.agent"));
  assert.equal(result.metadataLost, true);
  assert.deepEqual(result.config.wiring, { registrations: {}, resources: {} });
  assert.deepEqual(result.legacy!.wiring, { claude: { created: true, createdDir: false } });
  assert.deepEqual(parseConfig(serializeConfig(result.config), EN).axes, result.config.axes);

  const noMarker = JSON.parse(OLD_JSON);
  delete noMarker.schema;
  assert.deepEqual(recoverSettings(JSON.stringify(noMarker), EN)!.config.axes, result.config.axes);
});

test("old guard and width booleans are ignored in each supported schema while invalid obsolete input stays distinguishable", () => {
  for (const schema of [undefined, 1, 2]) {
    for (const obsolete of [undefined, false, true]) {
      const old = { ...JSON.parse(OLD_JSON), schema, fixed_width: obsolete, guards: obsolete,
        ...(schema === 2 ? { wiring: { registrations: {}, resources: {} } } : {}) };
      const text = JSON.stringify(old);
      const loaded = parseConfig(text, EN);
      assert.equal(Object.hasOwn(loaded, "fixed_width"), false);
      assert.equal(Object.hasOwn(loaded, "guards"), false);
      assert.deepEqual(loaded.axes, old.axes);
      assert.equal(loaded.safeword, old.safeword);
      const recovered = recoverSettings(text, EN)!;
      assert.deepEqual(recovered.invalid, []);
      assert.ok(!recovered.recovered.includes("fixed_width"));
      assert.ok(!recovered.defaulted!.includes("fixed_width"));
      assert.ok(!recovered.recovered.includes("guards"));
      assert.ok(!recovered.defaulted!.includes("guards"));
      assert.equal(Object.hasOwn(JSON.parse(serializeConfig(recovered.config, EN)), "fixed_width"), false);
      assert.equal(Object.hasOwn(JSON.parse(serializeConfig(recovered.config, EN)), "guards"), false);
    }
  }

  for (const field of ["fixed_width", "guards"]) {
    const damaged = { ...JSON.parse(OLD_JSON), [field]: "DUMMY_INVALID_OBSOLETE_VALUE" };
    assert.throws(() => parseConfig(JSON.stringify(damaged), EN), new RegExp(field));
    const recovered = recoverSettings(JSON.stringify(damaged), EN)!;
    assert.deepEqual(recovered.invalid, [field]);
    assert.ok(!recovered.defaulted!.includes(field));
    assert.ok(!recovered.recovered.includes(field));
    assert.deepEqual(recovered.config.axes, damaged.axes);
    assert.equal(recovered.config.safeword, damaged.safeword);
    assert.doesNotMatch(JSON.stringify(recovered), /DUMMY_INVALID_OBSOLETE_VALUE/);
  }

  const unrelated = JSON.stringify({ ...JSON.parse(OLD_JSON), fixed_width: true, unrecognizedWidth: true });
  assert.throws(() => parseConfig(unrelated, EN), /unrecognizedWidth/);
  assert.ok(recoverSettings(unrelated, EN)!.invalid.includes("unknown-fields"));
});

