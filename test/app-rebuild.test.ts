test("stale source and state-root overlap refuse before rebuilding", async () => {
  const f = fixture();
  try {
    const preset = userPreset(f);
    fs.writeFileSync(f.ctx.paths.config, "malformed dummy input");
    f.ctx.flags.fromPreset = "old-profile";
    const originalMkdir = fs.mkdirSync;
    const fault = mock.method(fs, "mkdirSync", (...args: Parameters<typeof fs.mkdirSync>) => {
      const result = originalMkdir(...args);
      if (String(args[0]) === f.ctx.paths.operationsLock) fs.writeFileSync(preset.path, JSON.stringify({ values: { care: 5 } }));
      return result;
    });
    syncBuiltinESMExports();
    try { await assert.rejects(() => runAppRebuild(f.ctx), /changed|stale/i); }
    finally { fault.mock.restore(); syncBuiltinESMExports(); }
    assert.equal(fs.readFileSync(f.ctx.paths.config, "utf8"), "malformed dummy input");
    assert.equal(fs.existsSync(f.ctx.paths.tone), false);
    assert.equal(inspectOperations(f.ctx.paths).lock.state, "none");
    f.ctx.cwd = f.root;
    await assert.rejects(() => runAppRebuild(f.ctx), /instruction|overlap/i);
    assert.equal(fs.existsSync(f.ctx.paths.agents), false);
    assert.equal(readJournal(f.ctx.paths, "0".repeat(32)), null);
  } finally { f.dispose(); }
});

test("selected dead mutation retires without certifying its writes, and new rebuild rollback cannot resurrect its lock", async () => {
  const f = fixture();
  try {
    const before = defaultConfig();
    before.persona.note = PRIVATE;
    fs.writeFileSync(f.ctx.paths.config, serializeConfig(before));
    const after = { ...before, axes: { ...oldAxes }, unsaved: true };
    const external = join(f.home, "unselected-project", "settings.json");
    fs.mkdirSync(join(f.home, "unselected-project"));
    fs.writeFileSync(external, JSON.stringify({ unrelated: PRIVATE }));
    const originalRename = fs.renameSync;
    const interruption = mock.method(fs, "renameSync", (from: fs.PathLike, to: fs.PathLike) => {
      originalRename(from, to);
      if (String(to) === f.ctx.paths.config) throw new Error("interrupted before completion checkpoint");
    });
    syncBuiltinESMExports();
    try {
      await assert.rejects(() => gate([
        planChange(external, () => JSON.stringify({ interruptedExternal: PRIVATE }), EN),
        planChange(f.ctx.paths.config, () => serializeConfig(after), EN, undefined, f.root),
      ],
        { paths: f.ctx.paths, auto: true, dryRun: false, ui: f.ctx.ui, t: EN, out: () => {} }), /interrupted/);
    } finally { interruption.mock.restore(); syncBuiltinESMExports(); }
    const pending = inspectOperations(f.ctx.paths).journals[0]!.journal!;
    assert.equal(pending.state, "pending");
    assert.deepEqual(pending.completed, [0]);
    f.ctx.flags.fromOperation = pending.operationId;
    await assert.rejects(() => runAppRebuild(f.ctx), error => error instanceof Error && error.message === EN.doctor.recoveryPending);
    assert.equal(fs.existsSync(f.ctx.paths.agents), false);
    const ownerPath = join(f.ctx.paths.operationsLock, "owner.json");
    const owner = JSON.parse(fs.readFileSync(ownerPath, "utf8"));
    owner.pid = 2_147_483_000;
    fs.writeFileSync(ownerPath, JSON.stringify(owner));
    const rebuilt = await runAppRebuild(f.ctx);
    const retired = readJournal(f.ctx.paths, pending.operationId)!;
    assert.equal(retired.state, "retired-for-app-rebuild");
    assert.deepEqual(retired.actions, pending.actions);
    assert.deepEqual(retired.completed, pending.completed);
    assert.equal(rebuilt.json.retiredOperation, pending.operationId);
    assert.equal(rebuilt.json.nativeAttention, true);
    assert.equal(rebuilt.json.retiredExternalActions, 1);
    assert.equal(JSON.parse(fs.readFileSync(external, "utf8")).interruptedExternal, PRIVATE);
    assert.notEqual(rebuilt.json.operationId, pending.operationId);
    assert.deepEqual(parseConfig(fs.readFileSync(f.ctx.paths.config, "utf8")).axes, oldAxes);
    assert.equal(fs.existsSync(f.ctx.paths.operationsLock), false);
    assert.equal(JSON.stringify({ lines: rebuilt.lines, json: rebuilt.json }).includes(PRIVATE), false);
    assert.equal(applyRollback(f.ctx.paths, rebuilt.json.operationId as string, EN).state, "rolled-back");
    assert.equal(readJournal(f.ctx.paths, pending.operationId)!.state, "retired-for-app-rebuild");
    assert.equal(fs.existsSync(f.ctx.paths.operationsLock), false);
    const again = await runAppRebuild(f.ctx);
    assert.equal(again.json.appRebuilt, true);
    assert.equal(fs.existsSync(f.ctx.paths.operationsLock), false);
  } finally { f.dispose(); }
});

