test("each selected level has a distinct anchor and the hook marker tracks verbosity and care", () => {
  const base = load("tough-love").config;
  for (const axis of AXIS_ORDER) {
    assert.equal(new Set(ANCHORS[axis]).size, 5, `${axis}: duplicate level anchor`);
    for (const level of [1, 2, 3, 4, 5] as const) {
      const axes = { ...base.axes, [axis]: level };
      const artifact = compile({ ...base, axes });
      const rules = artifact.split("### Rules\n")[1]!.split("### Controls")[0]!.split("\n");
      assert.equal(rules[AXIS_ORDER.indexOf(axis)], `- ${ANCHORS[axis][level - 1]}`, `${axis} ${level}`);
    }
  }
  const artifact = compile({ ...base, axes: { ...base.axes, verbosity: 1, care: 5 } });
  assert.match(artifact, /^<!-- generated by tonedial · preset: tough-love -->\n<!-- tonedial-style:1 verbosity=1 care=5 -->\n## Response tone\n/);
});

test("every axis pair and level pair compiles exactly without clamping or cross-axis rewriting", () => {
  const base = load("persona-leak-a").config;
  for (const [leftIndex, left] of AXIS_ORDER.entries()) {
    for (const right of AXIS_ORDER.slice(leftIndex + 1)) {
      for (const leftLevel of [1, 2, 3, 4, 5] as const) {
        for (const rightLevel of [1, 2, 3, 4, 5] as const) {
          const config = {
            ...base,
            axes: { ...AXIS_DEFAULT, [left]: leftLevel, [right]: rightLevel },
          };
          const before = structuredClone(config);
          const rules = compile(config).split("### Rules\n")[1]!.split("### Controls\n")[0]!.split("\n");
          assert.deepEqual(config, before, `${left}${leftLevel} × ${right}${rightLevel}: input mutated`);
          assert.equal(rules[AXIS_ORDER.indexOf(left)], `- ${ANCHORS[left][leftLevel - 1]}`);
          assert.equal(rules[AXIS_ORDER.indexOf(right)], `- ${ANCHORS[right][rightLevel - 1]}`);
          for (const axis of AXIS_ORDER.filter((axis): axis is Axis => axis !== left && axis !== right)) {
            assert.equal(rules[AXIS_ORDER.indexOf(axis)], `- ${ANCHORS[axis][AXIS_DEFAULT[axis] - 1]}`,
              `${left}${leftLevel} × ${right}${rightLevel}: ${axis} leaked`);
          }
        }
      }
    }
  }
});

test("all levels compile without guard folds or emergency tone release while keeping the controls and scope", () => {
  const base = load("tough-love").config;
  for (const level of [1, 2, 3, 4, 5] as const) {
    const config = { ...base, axes: Object.fromEntries(AXIS_ORDER.map(axis => [axis, level])) as Axes };
    const before = structuredClone(config);
    const artifact = compile(config);
    assert.deepEqual(config, before, `level ${level}: no lowering or mutation`);
    assert.doesNotMatch(artifact, /### Guards|Statements about work state|Flattery never distorts|On destructive-work warnings|never pretend to act|confess|correcting it|Keep bluffs|never at the person|situation only/);
    assert.match(artifact, /### Controls\n- Strong profanity, harsh mocking, fictional violent imagery, and theatrical menace are unconfirmed/);
    assert.match(artifact, /\n- Safeword:/);
    assert.match(artifact, /Warmth, praise, ordinary criticism, and ordinary role idioms need no confirmation/);
    assert.match(artifact, /never includes hate speech about protected traits or realistic or credible threats/);
    assert.match(artifact, /If the user asks to change the tone, use the `tonedial` CLI/);
    assert.match(artifact, /never changes\nwhat work is permitted, what approval is required/);
  }
});

test("advisory risk begins at each declared threshold and reports axes in display order", () => {
  const thresholds = { profanity: 4, critique: 4, flattery: 3, conviction: 5, compliance: 5, refusal: 2, bravado: 2 } as const;
  assert.deepEqual(riskyAxes(AXIS_DEFAULT), []);
  for (const [axis, threshold] of Object.entries(thresholds)) {
    assert.deepEqual(riskyAxes({ ...AXIS_DEFAULT, [axis]: threshold - 1 }), [], axis);
    assert.deepEqual(riskyAxes({ ...AXIS_DEFAULT, [axis]: threshold }), [axis], axis);
  }
  assert.deepEqual(riskyAxes(Object.fromEntries(AXIS_ORDER.map(axis => [axis, 5 as Level])) as Axes),
    ["profanity", "critique", "flattery", "conviction", "compliance", "refusal", "bravado"]);
});

