const FIXTURES = join(dirname(fileURLToPath(import.meta.url)), "fixtures");

const index = JSON.parse(readFileSync(join(FIXTURES, "index.json"), "utf8")) as {
  fixtures: string[];
};
assert.ok(index.fixtures.length > 0, "no compiler fixtures found");

const load = (name: string) => {
  const f = JSON.parse(readFileSync(join(FIXTURES, `${name}.config.json`), "utf8")) as {
    name: string;
    chars: number;
    config: Config;
  };
  return { ...f, artifact: readFileSync(join(FIXTURES, `${name}.tone.md`), "utf8") };
};

test("the compiler reproduces every current fixture byte for byte", () => {
  for (const name of index.fixtures) {
    const { config, artifact } = load(name);
    assert.equal(compile(config), artifact, `${name}: compiled output differs from the golden`);
  }
});

test("compiling is deterministic and does not touch the caller's config", () => {
  for (const name of index.fixtures) {
    const { config } = load(name);
    const snapshot = structuredClone(config);
    const first = compile(config);
    assert.deepEqual(config, snapshot, `${name}: compile mutated its argument`);
    assert.equal(compile(config), first, `${name}: two calls, two answers`);
  }
});

test("role idioms remain literal inputs as playfulness increases their requested frequency", () => {
  const base = load("right-hand").config;
  const persona = { ...base.persona!, agent: "함수를 담궈버릴까요? 아뢰옵기 황송하오나, 소인이 살펴보겠습니다." };
  const expectations = ["literal wording", "one light joke", "two role idioms", "most paragraphs", "nearly every sentence"];
  for (const [index, expected] of expectations.entries()) {
    const out = compile({ ...base, persona, axes: { ...base.axes, playfulness: index + 1 as Level, profanity: 1, bravado: 1 } });
    assert.ok(out.includes(expected), `playfulness ${index + 1}: missing frequency request`);
    assert.ok(out.includes(persona.agent), "a role expression was filtered or substituted");
    assert.ok(out.includes("allow role slang and metaphors"));
    assert.ok(out.includes("Do not exaggerate effort or claim credit"));
  }
});

