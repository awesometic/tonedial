import { compile, measure, type Config } from "../src/core/compile.ts";
import { ANCHORS, AXIS_DEFAULT, AXIS_ORDER, CAP_CHARS, PERSONA, riskyAxes, type Axes, type Level } from "../src/core/anchors.ts";
