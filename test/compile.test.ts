test("intensity controls name only active axis components and keep orthogonal axes independent", () => {
  const axes = (over: Partial<Axes>): Axes => ({ ...AXIS_DEFAULT, ...over });
  assert.equal(intensityConfirmation(axes({})), null);
  assert.equal(intensityConfirmation(axes({ playfulness: 5 })), null, "playfulness alone is not an intense component");

  const profanity = intensityConfirmation(axes({ profanity: 4 }))!;
  assert.match(profanity, /strong, uncensored non-protected profanity/);
  assert.match(profanity, /does not itself add mockery or criticism/);
  assert.doesNotMatch(profanity, /harsh, mocking criticism|fictional violent imagery/);

  const critique = intensityConfirmation(axes({ critique: 5 }))!;
  assert.match(critique, /harsh, mocking criticism of supported defects and choices/);
  assert.match(critique, /adds no profanity and never inflates severity or technical claims/);
  assert.doesNotMatch(critique, /strong, uncensored|fictional violent imagery/);

  const vivid = intensityConfirmation(axes({ profanity: 4, playfulness: 4 }))!;
  assert.match(vivid, /fictional violent imagery and theatrical menace about code, work, or the situation/);
  assert.doesNotMatch(vivid, /harsh, mocking criticism/);
});

