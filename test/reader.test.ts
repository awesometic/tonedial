test("Stop leaves an idle input pipe without waiting for its writer", async () => {
  writeFileSync(guidePath(), guide);
  writeFileSync(artifactPath(), "<!-- generated by tonedial · preset: kind -->\n" +
    "<!-- tonedial-style:1 verbosity=1 care=1 -->\n# Tone\n");
  const child = spawn(process.execPath, [script, "--provider", "codex", "--state", state, "--event", "Stop"], {
    env: { HOME: scratch, TMPDIR: scratch, PATH: "" },
    stdio: ["pipe", "pipe", "pipe"],
    timeout: 2000,
  });
  let output = "";
  child.stdout.setEncoding("utf8").on("data", (chunk) => { output += chunk; });
  child.stderr.resume();
  const code = await new Promise<number | null>((resolve, reject) => {
    child.once("error", reject);
    child.once("close", resolve);
  });
  assert.equal(code, 0, "the idle writer blocked the hook");
  assert.equal(output, "{}\n");
});

test("care5 feedback checks both organization and a functional emoji sequence", () => {
  writeFileSync(guidePath(), guide);
  writeFileSync(artifactPath(), "<!-- generated by tonedial · preset: kind -->\n" +
    "<!-- tonedial-style:1 verbosity=3 care=5 -->\n# Tone\n");
  const unmarked = "- item with enough detail to be substantial\n".repeat(5);
  let result = invoke("codex", ["--event", "Stop"], 5000, state, {}, JSON.stringify({
    last_assistant_message: unmarked,
    stop_hook_active: false,
  }));
  assert.equal(result.status, 0, result.error?.message ?? result.stderr);
  assert.match(result.stdout, /\"decision\":\"block\"/);
  assert.match(result.stdout, /functional emoji/);

  const onlyVariationSelector = "- item with enough detail to be substantial \uFE0F\n".repeat(5);
  result = invoke("codex", ["--event", "Stop"], 5000, state, {}, JSON.stringify({
    last_assistant_message: onlyVariationSelector,
    stop_hook_active: false,
  }));
  assert.equal(result.status, 0, result.error?.message ?? result.stderr);
  assert.match(result.stdout, /\"decision\":\"block\"/);

  const marked = "- ✅ item with enough detail to be substantial\n".repeat(5);
  result = invoke("codex", ["--event", "Stop"], 5000, state, {}, JSON.stringify({
    last_assistant_message: marked,
    stop_hook_active: false,
  }));
  assert.equal(result.status, 0, result.error?.message ?? result.stderr);
  assert.equal(result.stdout, "{}\n");
  assert.equal(result.stderr, "");

  const overlong = "- ✅ item with extra background and rationale that should be compressed.\n".repeat(12);
  writeFileSync(artifactPath(), "<!-- generated by tonedial · preset: kind -->\n" +
    "<!-- tonedial-style:1 verbosity=1 care=5 -->\n# Tone\n");
  result = invoke("codex", ["--event", "Stop"], 5000, state, {}, JSON.stringify({
    last_assistant_message: overlong,
    stop_hook_active: false,
  }));
  assert.equal(result.status, 0, result.error?.message ?? result.stderr);
  assert.match(result.stdout, /Compress unnecessary prose/);
  assert.doesNotMatch(result.stdout, /Add a functional emoji|Use concise organized items/);
});

